RANKED = ("capitals", "rivers", "authors", "dates", "persons", "scripture_and_antiquity")


def default_pattern(answer: str) -> str:
    stem = answer[:-1] if len(answer) >= 5 and answer[-1] in "aeoyi" else answer
    return re.escape(stem)


def key(fact: dict) -> re.Pattern:
    """The compiled pattern that accepts a fact's answer."""
    flags = re.I if fact["group"] == "nature_and_everyday" else 0
    return re.compile(rf"(?<!\w)(?:{fact['pattern']})", flags)


def facts() -> list[dict]:
    """Every fact: its group, its sentence openings, its question, its answer and its pattern."""
    out: list[dict] = []

    def add(group, prompts, question, answer, pattern):
        out.append({"group": group, "index": sum(f["group"] == group for f in out),
                    "prompts": prompts, "question": question, "answer": answer,
                    "pattern": pattern or default_pattern(answer)})

    for land, capital, pattern in CAPITALS:
        add("capitals", [f"Stolicą {land} jest", f"Głównem miastem {land} jest"],
            f"Jakie miasto jest stolicą {land}?", capital, pattern)
    for town, river, pattern in RIVERS:
        add("rivers", [f"{town} leży nad", f"Miasto {town} leży nad rzeką"],
            f"Nad jaką rzeką leży {town}?", river, pattern or RIVER_PATTERNS[river])
    for title, author in AUTHORS:
        woman = author in WOMEN
        add("authors",
            [f"{'Autorka' if woman else 'Autor'} dzieła „{title}” {'zwała' if woman else 'zwał'} się",
             f"Dzieło „{title}” {'napisała' if woman else 'napisał'}"],
            f"Kto napisał dzieło pod tytułem „{title}”?", author,
            AUTHOR_PATTERNS.get(author, ""))
    for event, year, also in DATES:
        add("dates", [f"{event[0].upper()}{event[1:]} w roku"], f"W którym roku {event}?",
            str(year), "|".join(rf"{y}\b" for y in (year, *also)))
    for prompt, question, answer, pattern in PERSONS:
        add("persons", [prompt], question, answer, pattern)
    for prompt, question, answer, pattern in SCRIPTURE_AND_ANTIQUITY:
        add("scripture_and_antiquity", [prompt], question, answer, pattern)
    for prompt, question, answer, pattern in NATURE_AND_EVERYDAY:
        add("nature_and_everyday", [prompt], question, answer, pattern)
    return out


def check() -> None:
    from collections import Counter

    from common import PeriodLexicon, words

    all_facts = facts()
    print({group: n for group, n in Counter(f["group"] for f in all_facts).items()},
          "total", len(all_facts))
    faults = []
    for fact in all_facts:
        accepts = key(fact)
        if not accepts.search(fact["answer"]):
            faults.append(("key rejects its own answer", fact["group"], fact["answer"]))
        for text in (*fact["prompts"], fact["question"]):
            if accepts.search(text):
                faults.append(("key matches the wording", fact["group"], text))
        for other in all_facts:
            if (other["group"] == fact["group"] and other["answer"] != fact["answer"]
                    and fact["group"] in RANKED and accepts.search(other["answer"])
                    and not key(other).search(fact["answer"])):
                faults.append(("key accepts another answer", fact["answer"], other["answer"]))
    for fault in sorted(set(faults)):
        print("FAULT", fault)

    lexicon = PeriodLexicon()
    wording = Counter()
    for fact in all_facts:
        for text in (*fact["prompts"], fact["question"], fact["answer"]):
            wording.update(words(text))
    found = lexicon.lookup(wording)
    rare = sorted((found.get(word, (0, 0))[1], word) for word in wording
                  if found.get(word, (0, 0))[1] < 200)
    print("words in fewer than 200 corpus documents:")
    for documents, word in rare:
        print(f"  {documents:>5}  {word}")
    answers = sorted({(found.get(w, (0, 0))[1], w) for fact in all_facts
                      for w in words(fact["answer"])})
    print("rarest answers:", answers[:25])


if __name__ == "__main__":
    check()
