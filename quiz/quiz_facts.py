"""Facts a reader of the period would have known, each with its answer key.

`fact_quiz.py` puts them to a model. Every fact is written twice: as the opening of a
sentence that the answer completes, which is how a base model is asked, and as a question,
which is how a chat model is asked. The wording keeps to the spelling of the corpus
(Francyi, komedya, polskiem), and the answers are those of the period: the capital of
Russia is Petersburg.

An answer is accepted by a pattern, matched at the start of a word, that covers its
inflected forms and the other spellings the period used (Szekspir and Shakespeare, tlen and
kwasoród). Where a fact gives no pattern, the answer itself is the pattern, less a final
vowel when it has five letters or more, so that `Kościuszko` also accepts `Kościuszki`.

Six of the seven groups hold answers of one kind (a city, a river, a surname, a year, a
name), so within them a model can also be asked to rank the right answer among all the
answers of its group. The seventh, on nature and everyday things, is mixed and is only
answered freely; its patterns ignore case, since such an answer may open a sentence.

Run directly, the module checks the keys and looks every word up in the corpus index:

    .venv/bin/python scripts/quiz_facts.py
"""

